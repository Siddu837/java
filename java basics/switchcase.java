public class switchcase {
    public static void main(String args[]){

        int num = 2;

        switch(num){
            case 1:
                System.out.println("eat");
                break;
               case 2:
                System.out.println("drink");
                break;  
            default: 
                System.out.println("not valid");
                break;

        }
    }
}
